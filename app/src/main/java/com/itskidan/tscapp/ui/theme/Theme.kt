// CompositionLocal to store padding
@Immutable
data class PaddingValues(
    val none: Dp = 0.dp,
    val extraSmall: Dp = 4.dp,
    val small: Dp = 8.dp,
    val medium: Dp = 16.dp,
    val large: Dp = 24.dp,
    val extraLarge: Dp = 32.dp,
    val statusBars: Dp = 0.dp,
    val navigationBars: Dp = 0.dp
)

val LocalPaddingValues = staticCompositionLocalOf { PaddingValues() }

@OptIn(ExperimentalMaterial3WindowSizeClassApi::class)
@Composable
fun AppTheme(
    paddingValues: PaddingValues = rememberDefaultPaddingValues(),
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit
) {
    val context = LocalContext.current
    val colorScheme = remember(context, darkTheme) {
        when {
            dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
                if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
            }

            darkTheme -> DarkColorScheme
            else -> LightColorScheme
        }
    }

    val windowSizeClass = if (LocalInspectionMode.current) {
        WindowWidthSizeClass.Compact
    } else {
        calculateWindowSizeClass(LocalContext.current as Activity).widthSizeClass
    }



    CompositionLocalProvider(
        LocalPaddingValues provides paddingValues,
        LocalWindowSizeClass provides windowSizeClass
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content
        )
    }
}

@Composable
fun rememberDefaultPaddingValues(): PaddingValues {
    val statusBars = WindowInsets.statusBars.asPaddingValues().calculateTopPadding()
    val navigationBars = WindowInsets.navigationBars.asPaddingValues().calculateBottomPadding()

    return PaddingValues(
        none = 0.dp,
        extraSmall = 4.dp,
        small = 8.dp,
        medium = 16.dp,
        large = 24.dp,
        extraLarge = 32.dp,
        statusBars = statusBars,
        navigationBars = navigationBars
    )
}